#!/usr/bin/env python3
"""Forgeline guard hooks. Stdlib only, fast, fail-open on internal errors.

Only active in repos that opted in (a .factory/config.json exists at or above cwd).
Profile: FORGELINE_HOOK_PROFILE env > .factory/config.json hooks.profile > "standard".

  minimal   destructive git, factory self-protection inside job worktrees
  standard  + generated-file protection, high-confidence secret detection, session briefing
  strict    + --no-verify, curl|sh, .env writes, broader secret patterns

Exit 2 + stderr blocks the tool call (Claude sees the reason and adapts).
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

LEVEL = {"minimal": 0, "standard": 1, "strict": 2}

SECRET_PATTERNS = [
    (r"AKIA[0-9A-Z]{16}", "AWS access key"),
    (r"-----BEGIN (RSA |EC |OPENSSH |DSA |PGP )?PRIVATE KEY-----", "private key"),
    (r"gh[pousr]_[A-Za-z0-9]{36,}", "GitHub token"),
    (r"github_pat_[A-Za-z0-9_]{60,}", "GitHub token"),
    (r"xox[abprs]-[A-Za-z0-9-]{10,}", "Slack token"),
    (r"sk-(ant-|proj-)?[A-Za-z0-9_-]{32,}", "API secret key"),
    (r"AIza[0-9A-Za-z_-]{35}", "Google API key"),
    (r"sk_live_[0-9a-zA-Z]{24,}", "Stripe live key"),
]
STRICT_SECRET_PATTERNS = [
    (r"(?i)(password|passwd|secret|api_?key|token)\s*[:=]\s*['\"][^'\"\s$]{8,}['\"]", "hard-coded credential"),
]
GENERATED_MARKERS = re.compile(r"Code generated .* DO NOT EDIT|@generated|<auto-generated|DO NOT EDIT\. Generated")
FACTORY_PROTECTED = re.compile(r"(^|/)\.factory/(checks\.sh|config\.json|pipeline\.json|state/)")


def find_factory(start: Path) -> Path | None:
    for p in (start, *start.parents):
        if (p / ".factory" / "config.json").exists():
            if p.parent.name == "worktrees" and p.parent.parent.name == ".factory":
                continue
            return p
    return None


def profile(repo: Path) -> int:
    env = os.environ.get("FORGELINE_HOOK_PROFILE")
    if env in LEVEL:
        return LEVEL[env]
    try:
        cfg = json.loads((repo / ".factory" / "config.json").read_text())
        return LEVEL.get((cfg.get("hooks") or {}).get("profile", "standard"), 1)
    except Exception:
        return 1


def base_branch(repo: Path) -> str:
    try:
        cfg = json.loads((repo / ".factory" / "config.json").read_text())
        return (cfg.get("vcs") or {}).get("base_branch", "main")
    except Exception:
        return "main"


def in_job_worktree(path: str, cwd: str) -> bool:
    return "/.factory/worktrees/" in (path or "") or "/.factory/worktrees/" in (cwd or "") + "/"


def is_factory_agent(data: dict) -> bool:
    """True for factory subagents / job worktrees. Humans driving Claude keep normal control."""
    return in_job_worktree("", data.get("cwd", "")) or str(data.get("agent_type") or "").startswith("forgeline")


def block(msg: str) -> None:
    print(f"[forgeline] blocked: {msg}", file=sys.stderr)
    sys.exit(2)


# ------------------------------------------------------------------ PreToolUse: Bash

def pre_bash(data: dict, repo: Path, level: int) -> None:
    cmd = (data.get("tool_input") or {}).get("command", "")
    flat = " ".join(cmd.split())
    base = base_branch(repo)

    if re.search(r"\bgit\s+push\b.*(\s--force(-with-lease)?\b|\s-f\b|\s\+\S)", flat):
        block("force push. Forgeline never rewrites shared history.")
    agent = is_factory_agent(data)
    if agent and re.search(rf"\bgit\s+push\b[^|;&]*\b(origin|upstream)\s+(HEAD:)?(refs/heads/)?({re.escape(base)}|main|master)\b", flat):
        block(f"push to the base branch ({base}). Work on the job branch; the factory merges after review.")
    if agent and re.search(r"\bgh\s+(pr\s+merge|issue\s+(close|edit))\b", flat):
        block("merging PRs or changing tickets from an agent. The factory does that after policy checks.")
    if re.search(r"\bgit\s+reset\s+--hard\b", flat) and not in_job_worktree("", data.get("cwd", "")):
        block("`git reset --hard` outside a job worktree would discard work.")
    if re.search(r"\brm\s+-[a-zA-Z]*r[a-zA-Z]*f?\s+(/|~|\$HOME|\.|\*)(\s|$)", flat):
        block("recursive delete of a root/home/current directory.")
    if re.search(r"(?i)\bdrop\s+(database|schema)\b", flat):
        block("DROP DATABASE/SCHEMA. Use migrations; never drop shared databases from an agent.")

    if agent and re.search(r"(>>?|\btee\s+(-a\s+)?|\bsed\s+-i[^|;&]*|\b(cp|mv|ln)\s+(-\S+\s+)*\S+\s+|\brm\s+(-\S+\s+)*)\s*\S*\.factory/(checks\.sh|config\.json|pipeline\.json|state/)", flat):
        block("modifying the factory gate/config from a job. Agents cannot change their own rules.")

    if level >= 2:
        if re.search(r"\bgit\s+commit\b.*--no-verify", flat):
            block("`git commit --no-verify` skips the repo's hooks (strict profile).")
        if re.search(r"\b(curl|wget)\b[^|]*\|\s*(sudo\s+)?(ba|z)?sh\b", flat):
            block("piping a download into a shell (strict profile).")


# ------------------------------------------------------------------ PreToolUse: Edit/Write

def pre_write(data: dict, repo: Path, level: int) -> None:
    ti = data.get("tool_input") or {}
    path = ti.get("file_path") or ti.get("path") or ""
    cwd = data.get("cwd", "")
    content = ti.get("content") or ti.get("new_string") or ""
    if isinstance(ti.get("edits"), list):
        content += "\n".join(e.get("new_string", "") for e in ti["edits"])

    if FACTORY_PROTECTED.search(path) and (in_job_worktree(path, cwd) or "/.factory/state/" in path and path.endswith("job.json")):
        block(f"{path} is factory configuration/state. Agents cannot edit the gate, policy or job state.")

    if level >= 1:
        p = Path(path)
        if p.exists() and p.is_file():
            try:
                head = "".join(p.open(errors="ignore").readlines()[:8])
            except OSError:
                head = ""
            if GENERATED_MARKERS.search(head):
                block(f"{path} is generated code. Change the source (SQL, schema, spec) and re-run the generator.")
        for pat, name in SECRET_PATTERNS + (STRICT_SECRET_PATTERNS if level >= 2 else []):
            if re.search(pat, content):
                block(f"content looks like a {name}. Use an environment variable or secret manager.")

    if level >= 2 and re.search(r"(^|/)\.env(\.[a-z]+)?$", path) and not path.endswith(".example"):
        block("writing a .env file (strict profile). Commit `.env.example` instead.")


# ------------------------------------------------------------------ PostToolUse: format hints

def post_write(data: dict, repo: Path, level: int) -> None:
    path = (data.get("tool_input") or {}).get("file_path", "")
    if level < 1 or not path.endswith(".go"):
        return
    try:
        out = subprocess.run(["gofmt", "-l", path], capture_output=True, text=True, timeout=10).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return
    if out:
        print(json.dumps({"hookSpecificOutput": {"hookEventName": "PostToolUse",
                                                 "additionalContext": f"{path} is not gofmt-formatted. Run `gofmt -w {path}`."}}))


# ------------------------------------------------------------------ SessionStart: briefing

def session_start(data: dict, repo: Path, level: int) -> None:
    if level < 1:
        return
    jobs_dir = repo / ".factory" / "state" / "jobs"
    counts: dict[str, int] = {}
    waiting = []
    if jobs_dir.exists():
        for jf in jobs_dir.glob("*/job.json"):
            try:
                j = json.loads(jf.read_text())
            except Exception:
                continue
            counts[j["status"]] = counts.get(j["status"], 0) + 1
            if j["status"] in ("awaiting_human", "blocked"):
                waiting.append(f"{j['id']} ({j['status']} at {j.get('paused_stage')})")
    msg = "Forgeline is active in this repo (.factory/). Commands: /forgeline:run, /forgeline:status, " \
          "/forgeline:approve. CLI: `forgeline`."
    if counts:
        msg += " Jobs: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())) + "."
    if waiting:
        msg += " Waiting on a human: " + "; ".join(waiting[:5]) + "."
    print(json.dumps({"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": msg}}))


HANDLERS = {"pre-bash": pre_bash, "pre-write": pre_write, "post-write": post_write, "session-start": session_start}


def main() -> None:
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    try:
        data = json.load(sys.stdin)
    except Exception:
        data = {}
    repo = find_factory(Path(data.get("cwd") or os.getcwd()).resolve())
    if repo is None or mode not in HANDLERS:
        return  # not a Forgeline repo: stay out of the way
    try:
        HANDLERS[mode](data, repo, profile(repo))
    except SystemExit:
        raise
    except Exception as e:  # never break the user's session because of a guard bug
        print(f"[forgeline] guard error ignored: {e}", file=sys.stderr)


if __name__ == "__main__":
    main()
